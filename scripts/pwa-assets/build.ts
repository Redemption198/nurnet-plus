/// <reference types="node" />
// The PWA's images, from the logo (app/assets/nurnet-plus.svg) and the brand gradient tokens.
// Run after changing either, or the numbers below: `vp run generate-pwa-assets` (macOS: the icons
// are rendered with sips; ffmpeg encodes the launch screens)
//
// The logo on its terracotta tile, at one proportion everywhere: the favicon, the home-screen and
// install icons, and the in-app brand button (BrandMark's symbol, which uses the same numbers).
// - public/favicon.svg
// - favicon-196.png, manifest-icon-{192,512}.png ("any": desktop installs, Chrome's splash): the
//   rounded tile on transparency, as the favicon
// - apple-icon-180.png: full bleed, iOS rounds it itself
// - manifest-icon-{192,512}.maskable.png: full bleed, the mark sized for the part every launcher
//   shows (the central 80%, W3C's safe zone), so it looks the same size as on the other tiles
//
// The iOS launch screens (utils/splashScreens.ts): the logo alone on the gradient, as the in-app
// splash (AppSplash) draws it, so one hands over to the other seamlessly
import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { SPLASH_SCREENS } from "../../app/utils/splashScreens.ts";

// The mark's width over the tile's, and the corner radius over the tile's side (the home-screen
// icon's squircle). Keep in step with BrandMark.vue
const MARK = 0.6;
const RADIUS = 0.225;
const SAFE_ZONE = 0.8;

const root = new URL("../../", import.meta.url);
const read = (path: string) => readFileSync(new URL(path, root), "utf8");

// The brand gradient, from its tokens in tailwind.css (bg-brand)
const css = read("app/assets/css/tailwind.css");
const token = (name: string) => css.match(new RegExp(`--color-${name}: (#[0-9a-f]{6});`))![1];
const stops = [token("brand-light"), token("terracotta"), token("brand-deep")];

// The logo's five circles, from the app's own SVG, and how far they reach
const logo = read("app/assets/nurnet-plus.svg");
const circles = [
  ...logo.matchAll(/<circle[^>]*?cx="([\d.]+)"[^>]*?cy="([\d.]+)"[^>]*?r="([\d.]+)"/gs),
].map(([, cx, cy, r]) => ({ cx: Number(cx), cy: Number(cy), r: Number(r) }));
const left = Math.min(...circles.map((c) => c.cx - c.r));
const right = Math.max(...circles.map((c) => c.cx + c.r));
const top = Math.min(...circles.map((c) => c.cy - c.r));
const bottom = Math.max(...circles.map((c) => c.cy + c.r));

// The tile in a 64-unit square: the mark `mark` wide, centred, on the gradient
function tile({ rounded, mark }: { rounded: boolean; mark: number }) {
  const scale = (64 * mark) / (right - left);
  const dx = 32 - ((left + right) / 2) * scale;
  const dy = 32 - ((top + bottom) / 2) * scale;
  const round = (n: number) => Number(n.toFixed(3));
  const dots = circles
    .map((c) => `<circle cx="${round(c.cx)}" cy="${round(c.cy)}" r="${round(c.r)}"/>`)
    .join("");
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64">
  <defs>
    <linearGradient id="g" x1="0" y1="0" x2="1" y2="1">
      ${stops.map((color, i) => `<stop offset="${i / 2}" stop-color="${color}"/>`).join("")}
    </linearGradient>
  </defs>
  <rect width="64" height="64"${rounded ? ` rx="${64 * RADIUS}"` : ""} fill="url(#g)"/>
  <g fill="#fff" transform="translate(${round(dx)} ${round(dy)}) scale(${round(scale)})">${dots}</g>
</svg>
`;
}

const rounded = tile({ rounded: true, mark: MARK });
writeFileSync(
  new URL("public/favicon.svg", root),
  rounded.replace(
    "<defs>",
    "<!-- NurNet+ favicon: the logo on its terracotta tile, as on the home screen and in the app.\n" +
      "       Generated by scripts/pwa-assets/build.ts (vp run generate-pwa-assets): edit that, not this -->\n  <defs>",
  ),
);

const outputs: [name: string, svg: string, size: number][] = [
  ["favicon-196.png", rounded, 196],
  ["manifest-icon-192.png", rounded, 192],
  ["manifest-icon-512.png", rounded, 512],
  ["apple-icon-180.png", tile({ rounded: false, mark: MARK }), 180],
  ["manifest-icon-192.maskable.png", tile({ rounded: false, mark: MARK * SAFE_ZONE }), 192],
  ["manifest-icon-512.maskable.png", tile({ rounded: false, mark: MARK * SAFE_ZONE }), 512],
];

// The launch screens are drawn here, pixel by pixel: the gradient as CSS draws "to right bottom"
// (a pixel's place along it is (x/w + y/h) / 2, mixed in sRGB), with ordered dithering. Rounded
// straight to 8 bits, the gradient across a whole screen falls into visible bands, worse once
// JPEG blocks them (steps of up to 3 levels); dithered, the steps stay under a third of a level.
// PNG, since lossy compression smooths the dither away. A 2×2 pattern smooths as well as a 4×4
// one at these pixel densities, and compresses to about half
const BAYER = [
  [0, 2],
  [3, 1],
].map((row) => row.map((v) => (v + 0.5) / 4 - 0.5));
const rgb = stops.map((hex) => [1, 3, 5].map((i) => Number.parseInt(hex.slice(i, i + 2), 16)));

function splash(width: number, height: number, ratio: number) {
  const [w, h] = [width * ratio, height * ratio];
  // As AppSplash: the logo's box min(36vw, 36vh, 200px), centred
  const box = Math.min(0.36 * width, 0.36 * height, 200) * ratio;
  const scale = box / 64;
  const [ox, oy] = [(w - box) / 2, (h - box) / 2];
  const dots = circles.map((c) => ({ x: ox + c.cx * scale, y: oy + c.cy * scale, r: c.r * scale }));

  const pixels = Buffer.alloc(w * h * 3);
  for (let y = 0; y < h; y++) {
    const inLogoRows = y >= oy - 1 && y <= oy + box + 1;
    for (let x = 0; x < w; x++) {
      const t = ((x + 0.5) / w + (y + 0.5) / h) / 2;
      const [from, to, u] = t < 0.5 ? [rgb[0]!, rgb[1]!, t * 2] : [rgb[1]!, rgb[2]!, t * 2 - 1];
      // White logo over the gradient, its edges antialiased by how much of the pixel it covers
      let cover = 0;
      if (inLogoRows && x >= ox - 1 && x <= ox + box + 1)
        for (const dot of dots)
          cover = Math.max(
            cover,
            Math.min(1, Math.max(0, dot.r - Math.hypot(x + 0.5 - dot.x, y + 0.5 - dot.y) + 0.5)),
          );
      for (let c = 0; c < 3; c++) {
        const ground = from[c]! + (to[c]! - from[c]!) * u + BAYER[y % 2]![x % 2]!;
        const value = ground * (1 - cover) + 255 * cover;
        pixels[(y * w + x) * 3 + c] = Math.max(0, Math.min(255, Math.round(value)));
      }
    }
  }
  return { pixels, w, h };
}

const work = mkdtempSync(join(tmpdir(), "pwa-assets-"));
try {
  for (const [name, svg, size] of outputs) {
    const source = join(work, `${name}.svg`);
    writeFileSync(source, svg);
    const out = new URL(`public/pwa/${name}`, root).pathname;
    execFileSync("sips", ["-s", "format", "png", "-Z", String(size), source, "--out", out], {
      stdio: "ignore",
    });
    console.log(`${name} (${size}px)`);
  }

  for (const { file, width, height, ratio } of SPLASH_SCREENS) {
    const { pixels, w, h } = splash(width, height, ratio);
    const raw = join(work, "splash.rgb");
    writeFileSync(raw, pixels);
    const out = new URL(`public/pwa/${file}`, root).pathname;
    // Raw RGB in, PNG out. Each pixel predicted from its left neighbour ("sub"): the smallest
    // files for a dithered gradient, a third smaller than ffmpeg's per-row "mixed"
    execFileSync("ffmpeg", [
      "-y",
      "-loglevel",
      "error",
      "-f",
      "rawvideo",
      "-pix_fmt",
      "rgb24",
      "-s",
      `${w}x${h}`,
      "-i",
      raw,
      "-pred",
      "sub",
      "-compression_level",
      "9",
      out,
    ]);
    console.log(file);
  }
} finally {
  rmSync(work, { recursive: true, force: true });
}
